/** 取一张卡；未知 id 落到默认卡（并由调用方在 diagnostics 里留痕）。 */
export function getPersonaCard(id) {
  const key = String(id || '').trim();
  return PERSONA_CARDS[key] || PERSONA_CARDS[DEFAULT_PERSONA_ID];
}

/** 卡 id 清单（给调用方/自测遍历用）。 */
export function listPersonaIds() {
  return Object.keys(PERSONA_CARDS);
}