export function promptSections(context = {}) {
  const cfg = readConfig() || {};

  // 会话闸：留空＝全部会话；写错格式就谁都匹配不上，等于只在私聊/群里都不生效。
  const only = String(cfg.onlyChatKeys || '')
    .split(/[,，\s]+/)
    .map((s) => s.trim())
    .filter(Boolean);
  if (only.length && !only.includes(String(context.chatKey || ''))) return [];

  const out = SECTIONS.map((s) => ({ ...s }));

  const note = String(cfg.extraNote || '').trim();
  if (note) {
    out.push({
      id: 'jailbreak-mode-extra',
      title: '补充要求',
      priority: 55,
      content: note
    });
  }

  return out;
}
